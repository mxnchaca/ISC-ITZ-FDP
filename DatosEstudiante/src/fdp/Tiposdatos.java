		System.out.print("------------------------------------------------\n");
		System.out.print("Integer =\t"+9876543+"\n");
		System.out.print("------------------------------------------------\n");
		System.out.print("float =\t\t"+12.35+"\n");
		System.out.print("------------------------------------------------\n");
		System.out.print("double =\t\t"+45.78+"\n");
